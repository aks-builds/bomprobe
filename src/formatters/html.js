const { countBySeverity, totalFindings } = require('../utils/severity');

function formatResult(result) {
  const counts = countBySeverity(result.checks);
  const total = totalFindings(result.checks);
  const scoreColor = result.score.overall >= 7 ? '#2d7d46' :
    result.score.overall >= 4 ? '#b8860b' : '#c0392b';

  let html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>bomprobe report</title>
<style>
body { font-family: system-ui, sans-serif; max-width: 800px; margin: 2rem auto; padding: 0 1rem; color: #333; }
h1 { border-bottom: 2px solid #eee; padding-bottom: 0.5rem; }
.score { font-size: 2rem; font-weight: bold; color: ${scoreColor}; }
.summary { display: flex; gap: 2rem; margin: 1rem 0; }
.summary div { padding: 0.5rem 1rem; border-radius: 4px; background: #f5f5f5; }
table { width: 100%; border-collapse: collapse; margin-top: 1rem; }
th, td { text-align: left; padding: 0.5rem; border-bottom: 1px solid #eee; }
th { background: #f9f9f9; }
.error { color: #c0392b; }
.warning { color: #b8860b; }
.info { color: #2980b9; }
</style>
</head>
<body>
<h1>bomprobe report</h1>
<p>File: <code>${result.file}</code> | Format: ${result.format} | Components: ${result.componentCount}</p>
<p class="score">${result.score.overall}/10</p>
<div class="summary">
<div class="error">Errors: ${counts.error || 0}</div>
<div class="warning">Warnings: ${counts.warning || 0}</div>
<div class="info">Info: ${counts.info || 0}</div>
</div>`;

  if (total > 0) {
    html += `\n<table>\n<tr><th>Check</th><th>Severity</th><th>Component</th><th>Message</th></tr>`;
    for (const check of result.checks) {
      for (const f of check.findings) {
        html += `\n<tr><td>${check.name}</td><td class="${f.severity}">${f.severity}</td><td>${f.component || '-'}</td><td>${f.message}</td></tr>`;
      }
    }
    html += `\n</table>`;
  } else {
    html += `\n<p>No findings. This SBOM looks great.</p>`;
  }

  html += `\n<footer style="margin-top:2rem;color:#999;font-size:0.85rem">Generated by bomprobe</footer>`;
  html += `\n</body>\n</html>`;

  return html;
}

module.exports = { formatResult };
