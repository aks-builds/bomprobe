function formatHtml(result) {
  const grade = result.score?.grade || 'N/A';
  const score = result.score?.overall ?? 'N/A';
  const errors = countBySeverity(result, 'error');
  const warnings = countBySeverity(result, 'warning');
  const infos = countBySeverity(result, 'info');

  const rows = [];
  for (const check of result.checks || []) {
    for (const f of check.findings || []) {
      rows.push(`<tr class="${f.severity}">
        <td>${esc(check.name || check.id)}</td>
        <td><span class="badge ${f.severity}">${f.severity}</span></td>
        <td>${esc(f.message)}</td>
      </tr>`);
    }
  }

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>bomprobe Report</title>
<style>
  body { font-family: system-ui, sans-serif; max-width: 900px; margin: 0 auto; padding: 20px; }
  h1 { border-bottom: 2px solid #333; padding-bottom: 8px; }
  .summary { display: flex; gap: 24px; margin: 16px 0; }
  .stat { text-align: center; }
  .stat .value { font-size: 2em; font-weight: bold; }
  .stat .label { font-size: 0.85em; color: #666; }
  table { width: 100%; border-collapse: collapse; margin-top: 16px; }
  th, td { text-align: left; padding: 8px 12px; border-bottom: 1px solid #ddd; }
  th { background: #f5f5f5; }
  .badge { padding: 2px 8px; border-radius: 4px; font-size: 0.8em; font-weight: 600; }
  .badge.error { background: #fee; color: #c33; }
  .badge.warning { background: #fff3cd; color: #856404; }
  .badge.info { background: #e8f4fd; color: #0c5460; }
  tr.error td:first-child { border-left: 3px solid #c33; }
  tr.warning td:first-child { border-left: 3px solid #856404; }
  tr.info td:first-child { border-left: 3px solid #0c5460; }
  .footer { margin-top: 24px; color: #999; font-size: 0.8em; }
</style>
</head>
<body>
<h1>bomprobe Report</h1>
<div class="summary">
  <div class="stat"><div class="value">${grade}</div><div class="label">Grade</div></div>
  <div class="stat"><div class="value">${score}</div><div class="label">Score</div></div>
  <div class="stat"><div class="value">${errors}</div><div class="label">Errors</div></div>
  <div class="stat"><div class="value">${warnings}</div><div class="label">Warnings</div></div>
  <div class="stat"><div class="value">${infos}</div><div class="label">Info</div></div>
</div>
${rows.length > 0 ? `<table>
<thead><tr><th>Check</th><th>Severity</th><th>Message</th></tr></thead>
<tbody>${rows.join('\n')}</tbody>
</table>` : '<p>No findings.</p>'}
<div class="footer">Generated by bomprobe</div>
</body>
</html>`;
}

function countBySeverity(result, severity) {
  let count = 0;
  for (const check of result.checks || []) {
    for (const f of check.findings || []) {
      if (f.severity === severity) count++;
    }
  }
  return count;
}

function esc(str) {
  return (str || '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

module.exports = { formatHtml };
