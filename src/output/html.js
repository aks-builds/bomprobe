function formatHtml(result) {
  const score = typeof result.score === 'object' ? result.score.overall : result.score;
  const grade = result.grade || '';
  const findings = (result.results || []).filter(r => r.findings.length > 0);
  const total = (result.results || []).length;

  const rows = [];
  for (const r of findings) {
    for (const f of r.findings) {
      const sev = f.severity || 'info';
      const cls = sev === 'error' ? 'err' : sev === 'warning' ? 'warn' : 'info';
      rows.push(`<tr class="${cls}"><td>${esc(r.name)}</td><td>${esc(sev)}</td><td>${esc(f.component || '')}</td><td>${esc(f.message || '')}</td></tr>`);
    }
  }

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>bomprobe audit report</title>
<style>
body{font-family:system-ui,sans-serif;max-width:900px;margin:2rem auto;padding:0 1rem;color:#1a1a1a}
h1{font-size:1.4rem}
.score{font-size:2rem;font-weight:700}
.grade{font-size:1.2rem;padding:.2rem .6rem;border-radius:4px;background:#e8e8e8;margin-left:.5rem}
table{width:100%;border-collapse:collapse;margin-top:1rem}
th,td{text-align:left;padding:.4rem .6rem;border-bottom:1px solid #ddd}
th{background:#f5f5f5}
.err td:nth-child(2){color:#d32f2f;font-weight:600}
.warn td:nth-child(2){color:#f57c00;font-weight:600}
.info td:nth-child(2){color:#1976d2}
.summary{margin-top:1.5rem;padding:1rem;background:#f9f9f9;border-radius:6px}
</style>
</head>
<body>
<h1>bomprobe audit report</h1>
<p><span class="score">${score}/100</span><span class="grade">${grade}</span></p>
<p>${total} checks run, ${findings.length} with findings</p>
${rows.length > 0 ? `<table>
<thead><tr><th>Check</th><th>Severity</th><th>Component</th><th>Detail</th></tr></thead>
<tbody>${rows.join('\n')}</tbody>
</table>` : '<p>All checks passed with no findings.</p>'}
<div class="summary">
<p>Generated by <strong>bomprobe</strong></p>
</div>
</body>
</html>`;
}

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

module.exports = { formatHtml };
